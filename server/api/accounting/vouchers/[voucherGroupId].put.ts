import { defineEventHandler, createError, readBody } from 'h3';
import mongoose from 'mongoose';
import Ledger from '../../../models/Ledger';
import { UnifiedPostingService } from '../../../utils/accounting/unified-posting.service';
import { convertVoucherInputToLegs, mapLegacyVoucherType } from '../../../utils/accounting/posting-adapter';
import { resolveVoucherLiquidityAccount } from '../../../utils/accounting/voucher-liquidity-account';
import { requireAuthSession } from '../../../utils/auth';
import { getSql, connectPostgres } from '../../../utils/pg.config';
import { connectDB } from '../../../plugins/mongodb';

export default defineEventHandler(async (event) => {
  const user = await requireAuthSession(event);
  const voucherGroupId = event.context.params?.voucherGroupId;
  if (!voucherGroupId || !voucherGroupId.trim()) {
    throw createError({ statusCode: 400, statusMessage: 'Voucher Group ID is required' });
  }

  const body = (await readBody(event)) || {};
  const { vtype, vdate, narration = '', entries, mainAccount } = body;

  if (!entries || !Array.isArray(entries) || entries.length === 0) {
    throw createError({ statusCode: 400, statusMessage: 'Voucher must contain at least one entry' });
  }
  const parsedTransactionDate = typeof vdate === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(vdate)
    ? new Date(`${vdate}T00:00:00.000Z`)
    : null;
  if (!parsedTransactionDate || Number.isNaN(parsedTransactionDate.getTime()) ||
      parsedTransactionDate.toISOString().slice(0, 10) !== vdate) {
    throw createError({ statusCode: 400, statusMessage: 'A valid transaction date is required in YYYY-MM-DD format' });
  }

  await connectDB();

  const firmIdObj = new mongoose.Types.ObjectId(String(user.firm_id));
  const transactionDate = vdate;
  const createdBy = user.username || user.email;
  if (!createdBy) {
    throw createError({ statusCode: 401, statusMessage: 'Authenticated user identity is required for voucher updates' });
  }

  // 1. Locate active existing entries in General Ledger
  const targetId = voucherGroupId.trim();
  let existingEntries = await Ledger.find({
    $or: [{ firmId: firmIdObj }, { firm_id: firmIdObj }],
    $and: [
      {
        $or: [
          { voucherGroupId: targetId },
          { voucherNo: targetId }
        ]
      },
      { isReversed: { $ne: true } }
    ]
  }).lean();

  if (!existingEntries || existingEntries.length === 0) {
    const altTarget = targetId.replace(/\//g, '-');
    existingEntries = await Ledger.find({
      $or: [{ firmId: firmIdObj }, { firm_id: firmIdObj }],
      $and: [
        {
          $or: [
            { voucherGroupId: altTarget },
            { voucherNo: altTarget }
          ]
        },
        { isReversed: { $ne: true } }
      ]
    }).lean();
  }

  // If not found as active, verify if it was reversed
  if (!existingEntries || existingEntries.length === 0) {
    const reversedCheck = await Ledger.find({
      $or: [{ firmId: firmIdObj }, { firm_id: firmIdObj }],
      $and: [
        {
          $or: [
            { voucherGroupId: targetId },
            { voucherNo: targetId },
            { voucherGroupId: targetId.replace(/\//g, '-') },
            { voucherNo: targetId.replace(/\//g, '-') }
          ]
        }
      ]
    }).lean();

    if (reversedCheck && reversedCheck.length > 0) {
      throw createError({ statusCode: 409, statusMessage: 'This voucher has been reversed and cannot be edited.' });
    }

    throw createError({ statusCode: 404, statusMessage: `Voucher "${voucherGroupId}" not found in General Ledger` });
  }

  const firstEntry = existingEntries[0]!;
  const canonicalVoucherGroupId = firstEntry.voucherGroupId || targetId;

  // 2. Subsystem integrity guards
  if (['BILL', 'SALE', 'PURCHASE'].includes(String(firstEntry.refType).toUpperCase())) {
    throw createError({
      statusCode: 400,
      statusMessage: 'This voucher was generated by a Commercial Bill. Please modify the bill in the Bills module to preserve inventory and GST integrity.'
    });
  }

  if (['WAGE', 'WAGE_PAYOUT'].includes(String(firstEntry.refType).toUpperCase())) {
    throw createError({
      statusCode: 400,
      statusMessage: 'This voucher was generated by the Wages & Payroll module. Please manage it through the Wages Hub.'
    });
  }

  // 3. PostgreSQL Database & Labor Cross-Module Verification
  let sql = getSql();
  if (!sql) sql = await connectPostgres();
  if (!sql) {
    throw createError({ statusCode: 503, statusMessage: 'PostgreSQL database connection is unavailable; voucher update was not performed.' });
  }

  // Guard: Settled labor periods must remain immutable
  const [linkedSettlement] = await sql`
    SELECT s.id, s.period_id FROM labor_settlements s
    JOIN labor_periods p ON p.id = s.period_id
    WHERE s.ledger_voucher_group_id = ${canonicalVoucherGroupId} AND p.firm_id = ${String(user.firm_id)}
    LIMIT 1
  `;
  if (linkedSettlement) {
    throw createError({
      statusCode: 409,
      statusMessage: 'This voucher is linked to an active Labor Settlement and cannot be edited. Please reopen/unsettle the period in the Labor module to make changes.'
    });
  }

  // Guard: Ensure existing advances are not locked in settled periods
  const existingAdvances = await sql`
    SELECT a.id, a.period_id, p.status as period_status
    FROM labor_advances a
    JOIN labor_periods p ON p.id = a.period_id
    WHERE a.ledger_voucher_group_id = ${canonicalVoucherGroupId} AND a.firm_id = ${String(user.firm_id)}
  `;
  const settledExisting = existingAdvances.find((a: any) => a.period_status === 'Settled');
  if (settledExisting) {
    throw createError({
      statusCode: 409,
      statusMessage: 'This voucher is linked to a settled labor period and cannot be edited. Please reopen the period in the Labor module to modify it.'
    });
  }

  // 4. Identify Labor Advance Legs in the incoming payload
  const normalizedVtype = (vtype || '').toUpperCase();
  const laborEntries = normalizedVtype === 'PAYMENT'
    ? entries
        .map((entry: any, legIndex: number) => ({ entry, legIndex, periodId: entry.laborPeriodId || body.laborPeriodId }))
        .filter(({ entry, periodId }: any) => periodId &&
          !/tds payable|tds borne by company/i.test(String(entry.accountHead || '')))
    : [];

  // Verify that any target labor periods exist and are Open
  for (const { entry, legIndex, periodId } of laborEntries) {
    const rawAmount = entry.amount !== undefined && entry.amount !== null ? entry.amount : entry.debitAmount;
    const amount = Number(rawAmount);
    if (rawAmount === undefined || rawAmount === null || rawAmount === '' || !Number.isFinite(amount) || amount <= 0) {
      throw createError({ statusCode: 400, statusMessage: `Labor-linked voucher entry ${legIndex + 1} must have a positive amount` });
    }
    const [period] = await sql`
      SELECT id, status FROM labor_periods
      WHERE id = ${periodId} AND firm_id = ${String(user.firm_id)}
    `;
    if (!period) {
      throw createError({ statusCode: 404, statusMessage: `Labor period "${periodId}" was not found in the current firm.` });
    }
    if (period.status === 'Settled') {
      throw createError({ statusCode: 409, statusMessage: `Labor period "${periodId}" is settled and cannot receive or modify advances.` });
    }
  }

  // 5. TDS Metadata Extraction & Validation for Labor Entries
  const tdsPayableEntry = entries.find((entry: any) => /tds payable/i.test(String(entry.accountHead || '')));
  const tdsBorneEntry = entries.find((entry: any) => /tds borne by company/i.test(String(entry.accountHead || '')));
  const tdsBorneCount = entries.filter((entry: any) => /tds borne by company/i.test(String(entry.accountHead || ''))).length;
  const tdsMode = tdsPayableEntry ? (tdsBorneEntry ? 'GROSS_UP' : 'DEDUCT') : 'NONE';
  const tdsAmount = tdsPayableEntry
    ? Math.abs(Number(tdsPayableEntry.amount ?? tdsPayableEntry.creditAmount))
    : 0;
  const tdsRate = tdsPayableEntry ? Number(tdsPayableEntry.statutory?.tdsRate) : 0;
  const tdsGrossAmount = tdsPayableEntry ? Number(tdsPayableEntry.statutory?.grossAmount) : 0;

  if (laborEntries.length > 0 && tdsBorneCount > 0 && !tdsPayableEntry) {
    throw createError({ statusCode: 400, statusMessage: 'Labor-linked TDS borne by the company requires a matching TDS payable leg.' });
  }

  // 6. Execute General Ledger Update in MongoDB
  const executeUpdate = async (session?: mongoose.ClientSession) => {
    const liquidityAccount = await resolveVoucherLiquidityAccount(mainAccount, firmIdObj, session);

    const legs = convertVoucherInputToLegs({
      vtype,
      entries,
      mainAccount: liquidityAccount?.accountHead,
      mainAccountType: liquidityAccount?.accountType,
      bankAccountId: liquidityAccount?.bankAccountId,
      narration,
    });

    const mappedType = mapLegacyVoucherType(vtype);

    const updateRes = await UnifiedPostingService.updateVoucher({
      firmId: firmIdObj,
      voucherGroupId: canonicalVoucherGroupId,
      payload: {
        firmId: firmIdObj,
        voucherType: mappedType,
        transactionDate,
        narration,
        legs,
        createdBy,
        refType: 'VOUCHER',
      },
      session
    });

    return {
      ...updateRes,
      bankAccountId: liquidityAccount?.bankAccountId ? String(liquidityAccount.bankAccountId) : null
    };
  };

  let mongoSession: mongoose.ClientSession | null = null;
  let updateResult: any;

  try {
    mongoSession = await mongoose.connection.startSession();
    mongoSession.startTransaction();
    updateResult = await executeUpdate(mongoSession);
    await mongoSession.commitTransaction();
  } catch (err: any) {
    if (mongoSession?.inTransaction()) {
      try {
        await mongoSession.abortTransaction();
      } catch (abortErr: any) {
        console.error('[Vouchers Put] Transaction abort failed:', abortErr);
      }
    }

    if (
      err.message?.includes('ClientSession must be from the same MongoClient') ||
      err.message?.includes('replica set') ||
      err.message?.includes('Transaction numbers')
    ) {
      console.warn('[Vouchers Put] Retrying update without transaction session:', err.message);
      updateResult = await executeUpdate(undefined);
    } else {
      console.error('[Vouchers Put] Error:', err);
      throw createError({
        statusCode: err.statusCode || 500,
        statusMessage: err.statusMessage || err.message || 'Failed to update voucher'
      });
    }
  } finally {
    if (mongoSession) {
      try { await mongoSession.endSession(); } catch (_) {}
    }
  }

  // 7. Synchronize PostgreSQL Labor Advances
  try {
    await sql.begin(async (tx: any) => {
      // Clean up previous advance records for this voucher
      await tx`
        DELETE FROM labor_advances
        WHERE ledger_voucher_group_id = ${canonicalVoucherGroupId} AND firm_id = ${String(user.firm_id)}
      `;

      if (laborEntries.length > 0) {
        const bankAccountId = updateResult.bankAccountId || null;
        const paymentMode = bankAccountId ? 'BANK' : 'CASH';

        for (const { entry, legIndex, periodId } of laborEntries) {
          const baseAmount = Number(entry.amount ?? entry.debitAmount);
          const periodAdvanceAmount = baseAmount;
          const currentGrossAmount = tdsMode === 'GROSS_UP' ? baseAmount + tdsAmount : baseAmount;
          const requestKey = `ADV-${canonicalVoucherGroupId}-${legIndex}`;

          await tx`
            INSERT INTO labor_advances (
              firm_id, period_id, amount, payment_date, payment_mode, paid_from_bank_account_id,
              ledger_voucher_group_id, idempotency_key, tds_mode, tds_rate, tds_amount, gross_amount, leg_index
            ) VALUES (
              ${String(user.firm_id)}, ${periodId}, ${periodAdvanceAmount}, ${transactionDate}, ${paymentMode},
              ${bankAccountId}, ${canonicalVoucherGroupId}, ${requestKey}, ${tdsMode},
              ${tdsRate}, ${tdsAmount}, ${currentGrossAmount}, ${legIndex}
            )
          `;
        }
      }
    });
  } catch (laborSyncErr: any) {
    console.error('[Dual-DB Sync Failure] Labor advance update sync failed:', laborSyncErr);
    throw createError({
      statusCode: laborSyncErr.statusCode || 500,
      statusMessage: `General Ledger updated (${updateResult.voucherNo}), but labor advance synchronization encountered an error: ${laborSyncErr.message}`
    });
  }

  return {
    success: true,
    message: `${vtype} voucher (${updateResult.voucherNo}) updated successfully`,
    data: {
      voucherGroupId: updateResult.voucherGroupId,
      voucherNo: updateResult.voucherNo,
      status: 'UPDATED'
    }
  };
});
