import { defineEventHandler, createError } from 'h3';
import mongoose from 'mongoose';
import Ledger from '../../../models/Ledger';
import { enforcePeriodLock } from '../../../utils/accounting/period-lock.service';
import { requireAuthSession } from '../../../utils/auth';
import { getSql, connectPostgres } from '../../../utils/pg.config';
import { connectDB } from '../../../plugins/mongodb';

export default defineEventHandler(async (event) => {
  try {
    const sessionUser = await requireAuthSession(event);
    const firmIdStr = String(sessionUser.firm_id);
    const firmIdObj = new mongoose.Types.ObjectId(firmIdStr);

    const voucherGroupId = event.context.params?.voucherGroupId;
    if (!voucherGroupId || !voucherGroupId.trim()) {
      throw createError({ statusCode: 400, statusMessage: 'Voucher Group ID is required' });
    }

    await connectDB();

    // 1. Locate existing entries for this voucher
    const targetId = voucherGroupId.trim();
    let entries = await Ledger.find({
      $or: [{ firmId: firmIdObj }, { firm_id: firmIdObj }],
      $and: [
        {
          $or: [
            { voucherGroupId: targetId },
            { voucherNo: targetId }
          ]
        }
      ]
    }).lean();

    if (!entries || entries.length === 0) {
      const altTarget = targetId.replace(/\//g, '-');
      entries = await Ledger.find({
        $or: [{ firmId: firmIdObj }, { firm_id: firmIdObj }],
        $and: [
          {
            $or: [
              { voucherGroupId: altTarget },
              { voucherNo: altTarget }
            ]
          }
        ]
      }).lean();
    }

    if (!entries || entries.length === 0) {
      throw createError({ statusCode: 404, statusMessage: `Voucher "${voucherGroupId}" not found in General Ledger` });
    }

    const firstEntry = entries[0]!;
    const canonicalVoucherGroupId = firstEntry.voucherGroupId || targetId;

    // 2. Period Lock Guard
    if (firstEntry.transactionDate) {
      await enforcePeriodLock(firmIdObj, firstEntry.transactionDate);
    }

    // 3. Subsystem integrity guards
    if (['BILL', 'SALE', 'PURCHASE'].includes(String(firstEntry.refType).toUpperCase())) {
      throw createError({
        statusCode: 400,
        statusMessage: 'This voucher was generated by a Commercial Bill. Please cancel the bill in the Bills module to preserve inventory and GST integrity.'
      });
    }

    // 4. Check if linked to an active PostgreSQL labor settlement
    try {
      let sql = getSql();
      if (!sql) sql = await connectPostgres();
      if (sql) {
        const [activeSettlement] = await sql`
          SELECT id, period_id FROM labor_settlements WHERE ledger_voucher_group_id = ${canonicalVoucherGroupId} LIMIT 1
        `;
        if (activeSettlement) {
          throw createError({
            statusCode: 400,
            statusMessage: 'This voucher is currently linked to an active Labor Settlement. Please use "Reopen / Unsettle Period" in the Labor module to safely cancel it.'
          });
        }
      }
    } catch (pgErr: any) {
      if (pgErr.statusCode) throw pgErr;
    }

    const body = (await readBody(event).catch(() => ({}))) || {};
    const cancellationReason = body.reason || 'Voucher cancelled via Voucher Manager';

    // 5. Explicit Double-Entry Reversal Counter-Voucher (Statutory Audit Immutability)
    const activeEntries = entries.filter((e: any) => e.isReversed !== true && !e.reversalVoucherGroupId);
    if (!activeEntries || activeEntries.length === 0) {
      throw createError({
        statusCode: 400,
        statusMessage: `Voucher "${canonicalVoucherGroupId}" is already cancelled or reversed.`
      });
    }

    const { UnifiedPostingService } = await import('../../../utils/accounting/unified-posting.service');

    let reversalResult: any;
    const executeReversal = async (mongoSession?: mongoose.ClientSession) => {
      const reversalLegs = activeEntries.map((orig: any) => ({
        accountHead: orig.accountHead,
        accountType: orig.accountType,
        debitAmount: orig.creditAmount || 0, // Swap: original CR -> reversal DR
        creditAmount: orig.debitAmount || 0, // Swap: original DR -> reversal CR
        narration: `REVERSAL OF VOUCHER ${canonicalVoucherGroupId}: ${orig.narration || ''}`.trim(),
        partyId: orig.partyId || null,
        bankAccountId: orig.bankAccountId || null,
        stockId: orig.stockId || null,
        stockRegId: orig.stockRegId || null,
        paymentMode: orig.paymentMode || undefined,
        isWageEntry: orig.isWageEntry,
        masterRollId: orig.masterRollId || null,
        statutory: orig.statutory || null,
        refId: orig.refId || null,
      }));

      reversalResult = await UnifiedPostingService.postVoucher(
        {
          firmId: firmIdObj,
          voucherType: (firstEntry.voucherType || 'JOURNAL') as any,
          transactionDate: new Date().toISOString().split('T')[0] as string,
          narration: `REVERSAL OF VOUCHER ${canonicalVoucherGroupId}: ${cancellationReason}`,
          legs: reversalLegs,
          createdBy: sessionUser.username || sessionUser.email || 'system',
          refType: 'VOUCHER_REVERSAL',
          refId: firstEntry.refId || undefined,
          externalVoucherGroupId: `REV-${canonicalVoucherGroupId}`,
          tags: {
            reversedVoucherGroupId: canonicalVoucherGroupId,
            isReversalVoucher: true,
          }
        },
        mongoSession
      );

      // Link original active ledger entries to the counter-voucher audit trail
      await Ledger.updateMany(
        {
          $or: [{ firmId: firmIdObj }, { firm_id: firmIdObj }],
          voucherGroupId: canonicalVoucherGroupId,
          reversalVoucherGroupId: { $exists: false }
        },
        {
          $set: {
            reversalVoucherGroupId: reversalResult.voucherGroupId,
            reversedAt: new Date(),
            reversedBy: sessionUser.username || sessionUser.email || 'system'
          }
        },
        mongoSession ? { session: mongoSession } : {}
      );
    };

    let mongoSession: mongoose.ClientSession | null = null;
    try {
      mongoSession = await mongoose.connection.startSession();
      mongoSession.startTransaction();
      await executeReversal(mongoSession);
      await mongoSession.commitTransaction();
    } catch (err: any) {
      if (mongoSession) {
        try { await mongoSession.abortTransaction(); } catch (_) {}
      }

      if (
        err.message?.includes('ClientSession must be from the same MongoClient') ||
        err.message?.includes('replica set') ||
        err.message?.includes('Transaction numbers')
      ) {
        console.error('[Vouchers Delete] MongoDB replica set transaction required:', err.message);
        throw createError({
          statusCode: 500,
          statusMessage: 'MongoDB replica set transactions are mandatory for voucher reversal to guarantee immutable double-entry counter-posting. Non-transactional execution is prohibited.'
        });
      } else {
        throw err;
      }
    } finally {
      if (mongoSession) {
        try { mongoSession.endSession(); } catch (_) {}
      }
    }

    // 6. Clean up any linked labor advances in PostgreSQL
    try {
      let sql = getSql();
      if (!sql) sql = await connectPostgres();
      if (sql) {
        await sql`
          DELETE FROM labor_advances 
          WHERE ledger_voucher_group_id = ${canonicalVoucherGroupId} AND firm_id = ${firmIdStr}
        `;
      }
    } catch (laborSyncErr) {
      console.warn('Cross-module labor advance cleanup notice:', laborSyncErr);
    }

    return {
      success: true,
      message: `Voucher ${canonicalVoucherGroupId} was reversed with counter-voucher ${reversalResult?.voucherGroupId || `REV-${canonicalVoucherGroupId}`} in compliance with audit trail standards.`,
      reversalVoucherGroupId: reversalResult?.voucherGroupId,
      reversedLegsCount: activeEntries.length
    };
  } catch (err: any) {
    console.error('Delete voucher error:', err);
    throw createError({
      statusCode: err.statusCode || 500,
      statusMessage: err.statusMessage || err.message || 'Failed to delete voucher'
    });
  }
});
